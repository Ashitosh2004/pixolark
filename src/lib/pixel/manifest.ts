/**
 * Signed room manifests — the portable, database-free identity of a room.
 *
 * A manifest is a public document the room owner signs with a dedicated ECDSA
 * P-256 signing key (kept locally, encrypted at rest in the recovery registry —
 * never sent to any backend). Anyone can verify a manifest anywhere: the
 * signature covers every field, so a directory file, a QR code, or a hand-pasted
 * copy are all equally trustworthy sources.
 *
 * Rules enforced here (see docs/PRODUCTION-PLAN.md):
 * - Private encryption keys, plaintext messages, secret invitation tokens and
 *   private membership credentials NEVER go into a manifest.
 * - Canonical JSON (recursively key-sorted, no whitespace) is what gets signed;
 *   verification recomputes it from the received fields, so any edit breaks it.
 * - Expired manifests are invalid everywhere; revocation = re-publish without
 *   the room or with a tombstone flag (directories are re-generated by owners).
 * - Room availability is a coordinator question, never a manifest question.
 */
import { b64url, fromB64url, te } from "./bytes";
import { sha256 } from "./crypto";
import { normalizeRoomId } from "./codec";

export const MANIFEST_ALG = "ES256-P256" as const;
/** Default validity of a published manifest (owners republish to renew). */
export const MANIFEST_TTL_MS = 30 * 24 * 60 * 60_000;

export interface RoomManifest {
  v: 1;
  alg: typeof MANIFEST_ALG;
  roomId: string; // canonical: "123456" | "PX-123456"
  name: string;
  desc: string;
  type: "public" | "private"; // directories list "public" only
  category: string;
  region: string; // country
  subRegion: string; // state ("" = any)
  city: string; // city ("" = any)
  languages: string[];
  /** Owner identity: id = hex fingerprint; signingKey = b64url raw EC point of the ECDSA public key. */
  owner: { id: string; signingKey: string };
  /** Host ECDH public-key commitment — the anchor joins authenticate against. */
  host: { commitment: string };
  /** Coordinator discovery info; may be empty when the room is created offline. */
  coordinator: { urls: string[] };
  capabilities: { media: boolean; stickers: boolean; history: boolean; slowMode: boolean; approval: boolean };
  /** Public invitation info — "code" means joiners still need the room code. No secret tokens here. */
  invitation: { method: "open" | "code" };
  /** Who may recover/re-register the room on a coordinator. */
  policy: { recovery: "owner-only" | "co-owner"; coOwners: string[] };
  createdAt: number;
  updatedAt: number;
  expiresAt: number;
  /** b64url ECDSA-P256 signature over the canonical JSON of every other field. */
  signature: string;
}

// ---------- canonical JSON (the bytes that are signed) ----------

function canonicalize(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === "object") {
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(value as Record<string, unknown>).sort()) {
      out[k] = canonicalize((value as Record<string, unknown>)[k]);
    }
    return out;
  }
  return value;
}

/** Canonical UTF-8 bytes of a manifest with its `signature` field removed. */
export function canonicalManifestBytes(m: RoomManifest): Uint8Array<ArrayBuffer> {
  const { signature: _omit, ...rest } = m;
  return te.encode(JSON.stringify(canonicalize(rest)));
}

// ---------- keys ----------

/** Owner signing subkey — separate from the ECDH identity; exportable so the
 *  recovery registry can wrap it into encrypted backups. Never sent anywhere. */
export async function generateSigningKey(): Promise<CryptoKeyPair> {
  return (await crypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, ["sign", "verify"])) as CryptoKeyPair;
}

export async function exportSigningPublicKeyRaw(pub: CryptoKey): Promise<Uint8Array<ArrayBuffer>> {
  return new Uint8Array(await crypto.subtle.exportKey("raw", pub));
}

export async function exportSigningPrivateKeyPkcs8(priv: CryptoKey): Promise<Uint8Array<ArrayBuffer>> {
  return new Uint8Array(await crypto.subtle.exportKey("pkcs8", priv));
}

export async function importSigningPrivateKeyPkcs8(raw: Uint8Array<ArrayBuffer>): Promise<CryptoKey> {
  return await crypto.subtle.importKey("pkcs8", raw, { name: "ECDSA", namedCurve: "P-256" }, true, ["sign"]);
}

function importVerifyKey(raw: Uint8Array<ArrayBuffer>): Promise<CryptoKey> {
  return crypto.subtle.importKey("raw", raw, { name: "ECDSA", namedCurve: "P-256" }, false, ["verify"]);
}

/** Stable owner fingerprint: short hash of the signing public key. */
export async function ownerFingerprint(signingPubRaw: Uint8Array<ArrayBuffer>): Promise<string> {
  return (await sha256(signingPubRaw)).slice(0, 10).reduce((s, b) => s + b.toString(16).padStart(2, "0"), "");
}

// ---------- sign / verify ----------

export async function signManifest(m: Omit<RoomManifest, "signature" | "alg" | "v">, priv: CryptoKey): Promise<RoomManifest> {
  const full: RoomManifest = { ...m, v: 1, alg: MANIFEST_ALG, signature: "" };
  const sig = await crypto.subtle.sign({ name: "ECDSA", hash: "SHA-256" }, priv, canonicalManifestBytes(full) as unknown as BufferSource);
  return { ...full, signature: b64url(new Uint8Array(sig)) };
}

export type ManifestCheck = { ok: true; manifest: RoomManifest } | { ok: false; reason: string };

/** Full verification: schema shape, signature, room-id shape, expiry. */
export async function verifyManifest(candidate: unknown, now = Date.now()): Promise<ManifestCheck> {
  const m = candidate as RoomManifest | null;
  if (!m || typeof m !== "object") return { ok: false, reason: "not a manifest" };
  if (m.v !== 1 || m.alg !== MANIFEST_ALG) return { ok: false, reason: "unsupported manifest version/algorithm" };
  if (!m.roomId || !m.name || !m.owner?.signingKey || !m.owner?.id || !m.host?.commitment) {
    return { ok: false, reason: "missing required fields" };
  }
  if (normalizeRoomId(m.roomId) !== m.roomId) return { ok: false, reason: "room id not canonical" };
  if (!Array.isArray(m.languages)) return { ok: false, reason: "languages must be a list" };
  if (!m.signature) return { ok: false, reason: "unsigned manifest" };
  if (typeof m.expiresAt !== "number" || m.expiresAt <= now) return { ok: false, reason: "manifest expired" };
  if (m.updatedAt < m.createdAt) return { ok: false, reason: "updated before created" };
  if (m.expiresAt - m.updatedAt > MANIFEST_TTL_MS + 60_000) return { ok: false, reason: "manifest validity exceeds policy" };
  let key: CryptoKey;
  try {
    key = await importVerifyKey(fromB64url(m.owner.signingKey));
  } catch {
    return { ok: false, reason: "bad owner signing key" };
  }
  try {
    const ok = await crypto.subtle.verify({ name: "ECDSA", hash: "SHA-256" }, key, fromB64url(m.signature) as unknown as BufferSource, canonicalManifestBytes(m) as unknown as BufferSource);
    return ok ? { ok: true, manifest: m } : { ok: false, reason: "signature mismatch — manifest was modified or is not from its claimed owner" };
  } catch {
    return { ok: false, reason: "malformed signature" };
  }
}

/** Independent check that the fingerprint in the manifest matches its key. */
export async function verifyOwnerFingerprint(m: RoomManifest): Promise<boolean> {
  try {
    return (await ownerFingerprint(fromB64url(m.owner.signingKey))) === m.owner.id;
  } catch {
    return false;
  }
}

// ---------- static room directory ----------

export interface DirectoryIndex {
  v: 1;
  generatedAt: number;
  /** Absolute URLs of sibling mirrors serving the same tree. */
  mirrors: string[];
  /** Section paths available under this root, e.g. "global/general.json". */
  sections: string[];
}

export interface DirectoryFile {
  v: 1;
  section: string; // "global/general", "countries/india", "cities/kolhapur", ...
  generatedAt: number;
  /** Every entry must individually pass verifyManifest; clients drop the rest. */
  rooms: RoomManifest[];
}

/** Directory file name for a manifest's coordinates. */
export function manifestSections(m: RoomManifest): string[] {
  const slug = (s: string) => s.trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const out = [`global/${slug(m.category) || "general"}`];
  if (m.region) out.push(`countries/${slug(m.region)}`);
  if (m.region && m.subRegion) out.push(`states/${slug(m.subRegion)}`);
  if (m.region && m.subRegion && m.city) out.push(`cities/${slug(m.city)}`);
  for (const lang of m.languages) if (lang) out.push(`languages/${slug(lang)}`);
  return [...new Set(out)];
}

export async function manifestIdOf(m: RoomManifest): Promise<string> {
  return (await sha256(canonicalManifestBytes(m))).slice(0, 8).reduce((s, b) => s + b.toString(16).padStart(2, "0"), "");
}
